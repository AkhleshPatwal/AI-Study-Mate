import React, { useState } from 'react';
import { useStudy } from '../context/StudyContext';
import { YouTubeResource } from '../types/study';
import { searchYouTubeApi } from '../services/api';
import {
  Youtube,
  Search,
  ExternalLink,
  Sparkles,
  Key,
  Clock,
  CheckCircle,
  Play,
} from 'lucide-react';

export const YouTubeResourcesView: React.FC = () => {
  const { currentPack, settings, setActiveTab } = useStudy();
  const resources: YouTubeResource[] = currentPack.youtubeResources || [];

  const [activeQuery, setActiveQuery] = useState(
    resources[0]?.searchQuery || `${currentPack.title} lecture video explanation`
  );
  const [searchResults, setSearchResults] = useState<YouTubeResource[]>(resources);
  const [isSearching, setIsSearching] = useState(false);

  const handleSearch = async (queryText: string) => {
    setActiveQuery(queryText);
    setIsSearching(true);
    try {
      const res = await searchYouTubeApi(queryText);
      if (res.success && res.videos.length > 0) {
        setSearchResults(res.videos);
      }
    } catch (e) {
      console.error(e);
    } finally {
      setIsSearching(false);
    }
  };

  return (
    <div className="space-y-6 animate-in fade-in duration-200">
      {/* Header */}
      <div className="p-5 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-lg font-bold text-slate-900 dark:text-white flex items-center gap-2">
            <Youtube className="w-5 h-5 text-rose-600" />
            <span>Learn on YouTube</span>
          </h2>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
            Curated high-yield video lectures, visual animations, and case study breakdowns
          </p>
        </div>

        {/* API key notice */}
        {!settings.youtubeApiKey ? (
          <button
            onClick={() => setActiveTab('settings')}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-semibold text-slate-600 dark:text-slate-300 hover:bg-slate-100 transition-colors"
          >
            <Key className="w-3.5 h-3.5 text-slate-400" />
            <span>Connect YouTube API (Optional)</span>
          </button>
        ) : (
          <span className="flex items-center gap-1.5 text-xs text-emerald-600 dark:text-emerald-400 font-semibold">
            <CheckCircle className="w-4 h-4" />
            <span>YouTube Data API Active</span>
          </span>
        )}
      </div>

      {/* Suggested Search Queries Generated by Gemini */}
      <div className="p-5 rounded-3xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs space-y-3">
        <span className="text-xs font-bold text-slate-700 dark:text-slate-300 uppercase tracking-wide flex items-center gap-1.5">
          <Sparkles className="w-3.5 h-3.5 text-amber-500" />
          <span>Gemini-Recommended Video Search Queries:</span>
        </span>

        <div className="flex flex-wrap gap-2">
          {resources.map((res) => (
            <button
              key={res.id}
              onClick={() => handleSearch(res.searchQuery)}
              className={`px-3 py-2 rounded-xl text-xs font-medium border text-left transition-all flex items-center gap-2 cursor-pointer ${
                activeQuery === res.searchQuery
                  ? 'bg-rose-50 dark:bg-rose-950/60 border-rose-400 dark:border-rose-800 text-rose-900 dark:text-rose-200 shadow-xs'
                  : 'bg-slate-50 dark:bg-slate-800/60 border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-100'
              }`}
            >
              <Search className="w-3.5 h-3.5 text-rose-500" />
              <span>{res.searchQuery}</span>
            </button>
          ))}
        </div>
      </div>

      {/* Video Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
        {searchResults.map((video) => {
          const directSearchUrl =
            video.videoUrl ||
            `https://www.youtube.com/results?search_query=${encodeURIComponent(
              video.searchQuery || video.title
            )}`;

          return (
            <div
              key={video.id}
              className="p-5 rounded-3xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 hover:border-rose-400 dark:hover:border-rose-600 hover:shadow-lg transition-all flex flex-col justify-between group"
            >
              <div className="space-y-3">
                {/* Thumbnail / Video Banner */}
                {video.thumbnailUrl ? (
                  <div className="relative rounded-2xl overflow-hidden aspect-video bg-slate-100 dark:bg-slate-800">
                    <img
                      src={video.thumbnailUrl}
                      alt={video.title}
                      className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
                    />
                    <div className="absolute inset-0 bg-black/20 group-hover:bg-black/40 transition-colors flex items-center justify-center">
                      <div className="w-10 h-10 rounded-full bg-rose-600 text-white flex items-center justify-center shadow-lg group-hover:scale-110 transition-transform">
                        <Play className="w-5 h-5 fill-white ml-0.5" />
                      </div>
                    </div>
                  </div>
                ) : (
                  <div className="rounded-2xl p-6 bg-gradient-to-br from-rose-900/10 to-slate-100 dark:to-slate-800/80 border border-rose-100 dark:border-rose-950 flex items-center justify-center text-rose-600">
                    <Youtube className="w-12 h-12" />
                  </div>
                )}

                {/* Details */}
                <div>
                  <h3 className="text-sm sm:text-base font-bold text-slate-900 dark:text-white line-clamp-2 group-hover:text-rose-600 dark:group-hover:text-rose-400 transition-colors">
                    {video.title}
                  </h3>
                  <p className="text-xs text-slate-500 dark:text-slate-400 font-medium mt-1">
                    {video.channel}
                  </p>
                </div>

                {video.topicRelevance && (
                  <p className="text-xs text-slate-600 dark:text-slate-400 line-clamp-2 leading-relaxed">
                    {video.topicRelevance}
                  </p>
                )}
              </div>

              {/* Action Button */}
              <div className="mt-5 pt-3 border-t border-slate-100 dark:border-slate-800 flex items-center justify-between text-xs">
                {video.duration ? (
                  <span className="flex items-center gap-1 text-[11px] text-slate-500">
                    <Clock className="w-3.5 h-3.5" />
                    <span>{video.duration}</span>
                  </span>
                ) : (
                  <span className="text-[11px] text-slate-400">Curated Tutorial</span>
                )}

                <a
                  href={directSearchUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-rose-600 hover:bg-rose-700 text-white font-semibold transition-all shadow-xs cursor-pointer"
                >
                  <span>Open on YouTube</span>
                  <ExternalLink className="w-3.5 h-3.5" />
                </a>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
